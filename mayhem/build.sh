#!/usr/bin/env bash
#
# mayhem/build.sh — build irqbalance's fuzz targets and its known-answer selftests.
#
# Runs inside the commit image (mayhem/Dockerfile) as `mayhem` in /mayhem. The base image exports
# CC/CXX/SANITIZER_FLAGS/LIB_FUZZING_ENGINE/STANDALONE_FUZZ_MAIN/SRC.
#
# Upstream builds with meson (or autotools), which only produce the daemon/UI executables. The
# harnesses need the daemon's and the UI's objects with `main` renamed, so this compiles upstream's
# own source lists (meson.build: irqbalance_sources, ui/*.c) directly, with the config.h that meson
# would generate for: glib + ncurses (UI and the control socket) + libnuma, no thermal/libcap-ng/
# systemd. Everything lands under mayhem/build/ (gitignored by mayhem/.gitignore).
#
#   mayhem/build/fuzz/        objects: $SANITIZER_FLAGS + SanCov  -> libFuzzer targets
#   mayhem/build/standalone/  objects: $SANITIZER_FLAGS           -> *-standalone reproducers
#   mayhem/build/afl/         objects: afl-clang-fast + $SANITIZER_FLAGS -> AFL target (UI)
#   mayhem/build/test/        objects: normal flags               -> selftests + daemon for test.sh
#   mayhem/out/               the binaries
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
: "${AFL_CC:=afl-clang-fast}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

cd "$SRC"
B="$SRC/mayhem/build"
OUT="$SRC/mayhem/out"
H="$SRC/mayhem/harness"
mkdir -p "$B/fuzz" "$B/standalone" "$B/afl" "$B/test" "$OUT"

# --- config.h, as meson.build's configuration_data() would write it --------------------------
version=$(sed -n "s/^ *version: *'\([^']*\)'.*/\1/p" meson.build | head -n1)
[ -n "$version" ] || { echo "cannot read version from meson.build" >&2; exit 1; }
cat > "$B/config.h.new" <<EOF
/* generated by mayhem/build.sh (equivalent of meson's configure_file) */
#define HAVE_GETOPT_LONG 1
#define HAVE_IRQBALANCEUI 1
#define HAVE_NUMA_H 1
#undef HAVE_THERMAL
#undef HAVE_LIBCAP_NG
#undef HAVE_LIBSYSTEMD
#define VERSION "$version"
EOF
# only touch config.h when it changes (keeps a re-run's compile cache valid)
cmp -s "$B/config.h.new" "$B/config.h" || mv "$B/config.h.new" "$B/config.h"
rm -f "$B/config.h.new"

GLIB_CFLAGS=$(pkg-config --cflags glib-2.0)
GLIB_LIBS=$(pkg-config --libs glib-2.0)
CURSES_CFLAGS=$(pkg-config --cflags ncursesw 2>/dev/null || pkg-config --cflags ncurses)
CURSES_LIBS=$(pkg-config --libs ncursesw 2>/dev/null || pkg-config --libs ncurses)
DAEMON_LIBS="$GLIB_LIBS -lnuma -lm"
UI_LIBS="$GLIB_LIBS $CURSES_LIBS"

# upstream meson.build: irqbalance_sources (thermal.c only when libnl is found; it is not here)
DAEMON_SRCS="activate.c bitmap.c classify.c cputree.c irqbalance.c irqlist.c numa.c placement.c procinterrupts.c"
UI_SRCS="ui/helpers.c ui/irqbalance-ui.c ui/ui.c"

# libc entry points mocked by the harness environments (see mayhem/harness/fuzz_env.h, ui_env.h)
DAEMON_WRAP="-Wl,--wrap=fopen,--wrap=opendir,--wrap=stat,--wrap=readlink,--wrap=accept,--wrap=recvmsg,--wrap=send"
UI_WRAP="-Wl,--wrap=socket,--wrap=connect,--wrap=sendmsg,--wrap=recv"

COMMON_CPPFLAGS="-D_GNU_SOURCE -I$B -I$SRC -I$SRC/ui -I$H $GLIB_CFLAGS $CURSES_CFLAGS"

# compile <cc> <objdir> <cflags> <src...>: upstream sources, main() renamed so harnesses can link them
compile() {
  local cc="$1" dir="$2" flags="$3"; shift 3
  local src obj extra pids=()
  for src in "$@"; do
    obj="$dir/$(echo "$src" | tr '/' '_' | sed 's/\.c$/.o/')"
    extra=""
    case "$src" in
      irqbalance.c) extra="-Dmain=irqbalance_main" ;;
      ui/irqbalance-ui.c) extra="-Dmain=irqbalance_ui_main" ;;
    esac
    # shellcheck disable=SC2086
    $cc $flags $COMMON_CPPFLAGS $extra -c "$src" -o "$obj" &
    pids+=($!)
    if [ "${#pids[@]}" -ge "$MAYHEM_JOBS" ]; then wait "${pids[0]}"; pids=("${pids[@]:1}"); fi
  done
  for p in "${pids[@]}"; do wait "$p"; done
}
objs() { local dir="$1"; shift; local s; for s in "$@"; do echo -n "$dir/$(echo "$s" | tr '/' '_' | sed 's/\.c$/.o/') "; done; }

# --- 1) sanitized project objects -------------------------------------------------------------
# UBSan relaxation (the only one): bitmap.h's fls() does `x <<= 4` etc. on a signed int, which
# overflows (shift-base) for every mask with a high nibble set, i.e. on nearly every input that parses
# a cpumask. That benign pattern would halt every run, so -fno-sanitize=shift-base; all other UBSan
# checks (incl. shift-exponent) and ASan stay on and halting.
UB_RELAX="-fno-sanitize=shift-base"
FUZZ_FLAGS="$SANITIZER_FLAGS $UB_RELAX $DEBUG_FLAGS -O1 -fsanitize=fuzzer-no-link"
SA_FLAGS="$SANITIZER_FLAGS $UB_RELAX $DEBUG_FLAGS -O1"
compile "$CC" "$B/fuzz" "$FUZZ_FLAGS" $DAEMON_SRCS
compile "$CC" "$B/standalone" "$SA_FLAGS" $DAEMON_SRCS
compile "$AFL_CC" "$B/afl" "$SA_FLAGS" $UI_SRCS

# harness-side objects (environment mocks and the LSan switch) are sanitized but not SanCov'd
$CC $SA_FLAGS $COMMON_CPPFLAGS -c "$H/fuzz_env.c" -o "$B/fuzz_env.o"
$CC $SA_FLAGS -x c -c "$SRC/mayhem/lsan_off.cc" -o "$B/lsan_off.o"
$CC $SA_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$B/standalone_main.o"
$AFL_CC $SA_FLAGS $COMMON_CPPFLAGS -c "$H/ui_env.c" -o "$B/afl/ui_env.o"
$AFL_CC $SA_FLAGS -x c -c "$SRC/mayhem/lsan_off.cc" -o "$B/afl/lsan_off.o"

# --- 2) libFuzzer targets + standalone reproducers --------------------------------------------
# link_daemon <name>: harness + daemon objects + fuzz_env
link_daemon() {
  local name="$1"
  # shellcheck disable=SC2046,SC2086
  $CC $FUZZ_FLAGS $COMMON_CPPFLAGS -c "$H/fuzz_$name.c" -o "$B/fuzz/fuzz_$name.o"
  # shellcheck disable=SC2046,SC2086
  $CC $FUZZ_FLAGS $LIB_FUZZING_ENGINE "$B/fuzz/fuzz_$name.o" "$B/fuzz_env.o" "$B/lsan_off.o" \
      $(objs "$B/fuzz" $DAEMON_SRCS) $DAEMON_WRAP $DAEMON_LIBS -o "$OUT/fuzz_$name"
  # shellcheck disable=SC2046,SC2086
  $CC $SA_FLAGS $COMMON_CPPFLAGS -c "$H/fuzz_$name.c" -o "$B/standalone/fuzz_$name.o"
  # shellcheck disable=SC2046,SC2086
  $CC $SA_FLAGS "$B/standalone_main.o" "$B/standalone/fuzz_$name.o" "$B/fuzz_env.o" "$B/lsan_off.o" \
      $(objs "$B/standalone" $DAEMON_SRCS) $DAEMON_WRAP $DAEMON_LIBS -o "$OUT/fuzz_$name-standalone"
}
link_daemon procinterrupts
link_daemon sock_handle

# cpumask: bitmap.c alone (the parsers need nothing else)
# shellcheck disable=SC2086
$CC $FUZZ_FLAGS $COMMON_CPPFLAGS -c "$H/fuzz_cpumask.c" -o "$B/fuzz/fuzz_cpumask.o"
# shellcheck disable=SC2086
$CC $FUZZ_FLAGS $LIB_FUZZING_ENGINE "$B/fuzz/fuzz_cpumask.o" "$B/fuzz/bitmap.o" "$B/lsan_off.o" \
    -o "$OUT/fuzz_cpumask"
# shellcheck disable=SC2086
$CC $SA_FLAGS $COMMON_CPPFLAGS -c "$H/fuzz_cpumask.c" -o "$B/standalone/fuzz_cpumask.o"
# shellcheck disable=SC2086
$CC $SA_FLAGS "$B/standalone_main.o" "$B/standalone/fuzz_cpumask.o" "$B/standalone/bitmap.o" \
    "$B/lsan_off.o" -o "$OUT/fuzz_cpumask-standalone"

# --- 3) AFL target: irqbalance-ui reply parsing (file input; its own reproducer) ---------------
# shellcheck disable=SC2086
$AFL_CC $SA_FLAGS $COMMON_CPPFLAGS -c "$H/fuzz_ui_parse.c" -o "$B/afl/fuzz_ui_parse.o"
# shellcheck disable=SC2046,SC2086
$AFL_CC $SA_FLAGS "$B/afl/fuzz_ui_parse.o" "$B/afl/ui_env.o" "$B/afl/lsan_off.o" \
    $(objs "$B/afl" $UI_SRCS) $UI_WRAP $UI_LIBS -o "$OUT/fuzz_ui_parse"

# --- 4) the test build: normal flags, no sanitizers ---------------------------------------------
TEST_FLAGS="-O2 -g $COVERAGE_FLAGS"
compile "$CC" "$B/test" "$TEST_FLAGS" $DAEMON_SRCS $UI_SRCS
# shellcheck disable=SC2086
$CC $TEST_FLAGS $COMMON_CPPFLAGS -c "$H/fuzz_env.c" -o "$B/test/fuzz_env.o"
# shellcheck disable=SC2086
$CC $TEST_FLAGS $COMMON_CPPFLAGS -c "$H/selftest.c" -o "$B/test/selftest.o"
# shellcheck disable=SC2046,SC2086
$CC $TEST_FLAGS "$B/test/selftest.o" "$B/test/fuzz_env.o" $(objs "$B/test" $DAEMON_SRCS) \
    $DAEMON_WRAP $DAEMON_LIBS -o "$OUT/selftest"
# shellcheck disable=SC2086
$CC $TEST_FLAGS $COMMON_CPPFLAGS -c "$H/ui_env.c" -o "$B/test/ui_env.o"
# shellcheck disable=SC2086
$CC $TEST_FLAGS $COMMON_CPPFLAGS -c "$H/ui_selftest.c" -o "$B/test/ui_selftest.o"
# shellcheck disable=SC2046,SC2086
$CC $TEST_FLAGS "$B/test/ui_selftest.o" "$B/test/ui_env.o" $(objs "$B/test" $UI_SRCS) \
    $UI_WRAP $UI_LIBS -o "$OUT/ui_selftest"
# the real daemon executable (upstream main), for its --version check
# shellcheck disable=SC2086
$CC $TEST_FLAGS $COMMON_CPPFLAGS -c irqbalance.c -o "$B/test/irqbalance_main.o"
# shellcheck disable=SC2046,SC2086
$CC $TEST_FLAGS "$B/test/irqbalance_main.o" $(objs "$B/test" $(echo $DAEMON_SRCS | sed 's/irqbalance\.c//')) \
    $DAEMON_LIBS -o "$OUT/irqbalance"

for f in fuzz_procinterrupts fuzz_procinterrupts-standalone fuzz_sock_handle fuzz_sock_handle-standalone \
         fuzz_cpumask fuzz_cpumask-standalone fuzz_ui_parse selftest ui_selftest irqbalance; do
  [ -x "$OUT/$f" ] || { echo "missing $OUT/$f" >&2; exit 1; }
done
echo "build.sh: OK"
